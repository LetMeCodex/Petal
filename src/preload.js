const { contextBridge, ipcRenderer, webUtils } = require('electron');

const on = (channel, fn) => ipcRenderer.on(channel, (_e, ...args) => fn(...args));

contextBridge.exposeInMainWorld('petal', {
  // wheel
  onOpen: (fn) => on('wheel:open', fn),
  onClose: (fn) => on('wheel:close', fn),
  onBackdrop: (fn) => on('wheel:backdrop', fn),
  pathFor: (file) => webUtils.getPathForFile(file),
  dropped: () => ipcRenderer.send('wheel:dropped'),
  done: () => ipcRenderer.send('wheel:done'),
  run: (action, paths, options) => ipcRenderer.invoke('action:run', { action, paths, options }),
  onProgress: (fn) => on('action:progress', fn),
  log: (...args) => ipcRenderer.send('debug:log', args.join(' ')),
  // island
  island: {
    onDrag: (fn) => on('island:drag', fn),
    onCursor: (fn) => on('island:cursor', fn),
    onBackdrop: (fn) => on('island:backdrop', fn),
    onExternal: (fn) => on('island:external', fn),
    onMoved: (fn) => on('island:moved', fn),
    onLayout: (fn) => on('island:layout', fn),
    onNearTop: (fn) => on('island:nearTop', fn),
    onStats: (fn) => on('island:stats', fn),
    onPrefsChanged: (fn) => on('island:prefsChanged', fn),
    wantStats: (want) => ipcRenderer.send('island:wantStats', want),
    prefs: () => ipcRenderer.invoke('island:prefs'),
    setPrefs: (patch) => ipcRenderer.send('island:setPrefs', patch),
    resetPosition: () => ipcRenderer.send('island:resetPosition'),
    moveTo: (pt) => ipcRenderer.send('island:moveTo', pt),
    moveEnd: (pt) => ipcRenderer.send('island:moveEnd', pt),
    state: (s) => ipcRenderer.send('island:state', s),
    interactive: (on2) => ipcRenderer.send('island:interactive', on2),
    dropped: () => ipcRenderer.send('island:dropped'),
    wantBackdrop: () => ipcRenderer.send('island:wantBackdrop'),
    recent: () => ipcRenderer.invoke('island:recent'),
    startDrag: (file) => ipcRenderer.send('island:startDrag', file),
    open: (file) => ipcRenderer.send('island:open', file),
    reveal: (file) => ipcRenderer.send('island:reveal', file),
    copy: (text) => ipcRenderer.send('island:copy', text),
    settings: () => ipcRenderer.send('island:settings'),
  },
  // Ask
  ask: {
    onOpen: (fn) => on('ask:open', fn),
    onClose: (fn) => on('ask:close', fn),
    onBlur: (fn) => on('ask:blur', fn),
    onEvent: (fn) => on('ask:event', fn),
    request: () => ipcRenderer.send('ask:request'),
    closed: () => ipcRenderer.send('ask:closed'),
    query: (id, text) => ipcRenderer.send('ask:query', { id, text }),
    trash: (items, allow) => ipcRenderer.invoke('ask:trash', { items, allow }),
    undo: (batchId) => ipcRenderer.invoke('ask:undo', batchId),
    purge: (batchId) => ipcRenderer.invoke('ask:purge', batchId),
    reveal: (file) => ipcRenderer.send('ask:reveal', file),
    openFile: (file) => ipcRenderer.send('ask:openFile', file),
    setKey: (key) => ipcRenderer.invoke('ask:setKey', key),
    key: () => ipcRenderer.invoke('ask:key'),
    captureKey: () => ipcRenderer.invoke('ask:captureKey'),
  },
  // editors
  editorLoad: () => ipcRenderer.invoke('editor:load'),
  editorSave: (outputs) => ipcRenderer.invoke('editor:save', outputs),
  editorClose: () => ipcRenderer.send('editor:close'),
  reveal: (file) => ipcRenderer.send('editor:reveal', file),
  // settings / onboarding
  getSettings: () => ipcRenderer.invoke('settings:get'),
  setSettings: (patch) => ipcRenderer.invoke('settings:set', patch),
  captureKey: (fn) => { ipcRenderer.once('settings:keyCaptured', (_e, k) => fn(k)); ipcRenderer.send('settings:captureKey'); },
  startSampleDrag: () => ipcRenderer.send('onboarding:startDrag'),
  finishOnboarding: () => ipcRenderer.send('onboarding:finish'),
  onIslandSwitched: (fn) => on('settings:island', fn),
});
